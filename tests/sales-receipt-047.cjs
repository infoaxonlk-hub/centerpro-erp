const fs = require('node:fs');
const assert = require('node:assert/strict');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const read = (p) => fs.readFileSync(path.join(root, p), 'utf8');
const route = read('app/dashboard/sales/[id]/page.tsx');
const preview = read('app/dashboard/sales/sales-receipt-preview.tsx');
const css = read('app/dashboard/sales/sales-receipt-preview.css');
const bill = read('components/bill.tsx');
const pos = read('app/dashboard/sales/sales-pos.tsx');
const offline = read('lib/offline-pos.ts');
assert.match(pos, /window\.location\.assign\("\/dashboard\/sales\/"\+data\)/, 'Confirmed POS sales must still open the persisted sale route');
assert.match(pos, /window\.location\.assign\("\/dashboard\/sales\/"\+id\)/, 'Synced offline POS sales must open the persisted sale route');
assert.match(route, /<SalesReceiptPreview/, 'Sales detail route renders POS receipt preview');
assert.doesNotMatch(route, /<BillDetail|Invoice <strong>|SALES INVOICE|invoice\.invoice_number/, 'No old invoice preview or invoice identifier on POS receipt route');
assert.match(route, /number: r\.sale_number/, 'Receipt uses sale number, not invoice number');
assert.match(route, /r\.sales_order_lines\.map/, 'Receipt must contain item lines');
assert.match(route, /r\.sales_payments\.map/, 'Receipt must contain payment allocations');
assert.match(route, /credit: Number\(r\.credit_balance\)/, 'Customer credit amount is preserved');
assert.match(route, /requirePermission\("sales"\)/, 'Existing access policy is retained');
assert.match(route, /bill_returns/, 'Existing return requests are retained');
assert.match(preview, /<Bill data=\{\{ \.\.\.bill, language \}\}/, 'Reuse standard thermal Bill with EN/SI selection');
assert.match(preview, /onClick=\{\(\) => window\.print\(\)\}/, 'Receipt printing is manual');
assert.ok(!preview.includes('useEffect'), 'Receipt must not auto-print');
const order = ['Print receipt', '+ New sale', '<RequestBillReturn', '<CancelBill'];
let last = -1;
for (const marker of order) { const index = preview.indexOf(marker); assert.ok(index > last, `Action order: ${marker}`); last = index; }
assert.match(preview, /href="\/dashboard\/sales\/receivables"/, 'Credit settlement remains reachable');
assert.match(css, /@media\s+print/, 'Print layout included');
assert.match(css, /@media\(max-width:600px\)/, 'Mobile action layout included');
assert.match(bill, /"SALES RECEIPT":"විකුණුම් රිසිට්පත"/, 'Sinhala receipt heading supported');
assert.match(offline, /sale/, 'Offline sale support retained');
console.log('PASS — Update 047 POS receipt preview, payment data, manual printing, mobile actions, localization, and offline flow');
