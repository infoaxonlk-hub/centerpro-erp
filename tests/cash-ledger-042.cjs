const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '..');
const src = (f) => fs.readFileSync(path.join(root, f), 'utf8');
const nav = src('components/sidebar-navigation.tsx');
const page = src('app/dashboard/cash/ledger/page.tsx');
const sql = src('supabase/migrations/042_center_cash_ledger_readonly.sql');
const css = src('app/dashboard/cash/ledger/cash-ledger.css');
assert.match(nav, /href: "\/dashboard\/cash\/ledger", label: "Cash Ledger"/);
assert.match(page, /requirePermission\("cash"\)/);
assert.match(page, /\.eq\("user_id", profile\.id\)/);
assert.match(page, /isSuperAdmin \|\| allowedIds\.has\(c\.id\)/);
assert.match(page, /supabase\.rpc\("center_cash_general_ledger"/);
assert.match(page, /\.eq\("center_id", chosen\.id\)/);
assert.match(page, /Opening balance/);
assert.match(page, /Running balance/);
assert.match(page, /Debit \(LKR\)/);
assert.match(page, /Credit \(LKR\)/);
assert.match(page, /row\.description/);
assert.match(page, /row\.reference/);
assert.match(sql, /NOT EXISTS \([\s\S]*?public\.user_center_access/);
assert.match(sql, /v_role <> 'super_admin'/);
assert.match(sql, /cash_account_entries e/);
assert.match(sql, /OVER \(ORDER BY e\.created_at, e\.id/);
assert.ok(sql.indexOf('OVER (ORDER BY e.created_at, e.id') < sql.indexOf('WHERE (p_from IS NULL'), 'Running balance must be computed before date filtering');
assert.match(sql, /GRANT EXECUTE ON FUNCTION public\.center_cash_general_ledger/);
assert.ok(css.length > 200);
// Debit increases center cash; credit reduces it; opening remains stable across pages.
const posted = [{debit: 500, credit:0}, {debit:0, credit:120}, {debit:50,credit:0}];
let bal = 0;
const results = posted.map(row => bal += row.debit - row.credit);
assert.deepEqual(results, [500,380,430]);
assert.equal(results[2] - posted[2].debit + posted[2].credit, 380);
console.log('PASS: Center-restricted cash ledger, debit/credit/running balance, date/page-safe journal view.');
